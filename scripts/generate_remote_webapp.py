#!/usr/bin/env python3
"""Builds src/network/remote_control_webapp.h from src/network/webapp/.

The Remote Control web app is edited as ordinary index.html/app.css/app.js
files; this inlines the stylesheet and script into the page and emits it as
one C string literal served at "/". Run from the repository root (the Makefile
regenerates the header whenever a source file changes).
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "src", "network", "webapp")
OUT = os.path.join(ROOT, "src", "network", "remote_control_webapp.h")


def read(name):
    with open(os.path.join(SRC, name), encoding="utf-8") as f:
        return f.read()


def compact_css(css):
    css = re.sub(r"/\*.*?\*/", "", css, flags=re.S)
    css = re.sub(r"\s+", " ", css)
    css = re.sub(r"\s*([{};,>])\s*", r"\1", css)
    return css.replace(";}", "}").strip()


def compact_js(js):
    # Only indentation and blank lines go: the script stays readable in a
    # browser's devtools and no tokenizer is needed to stay correct.
    lines = (line.strip() for line in js.splitlines())
    return "\n".join(line for line in lines if line)


def c_literal_lines(text, width=110):
    out, current = [], ""
    for ch in text:
        if ch == "\\":
            piece = "\\\\"
        elif ch == '"':
            piece = '\\"'
        elif ch == "\n":
            piece = "\\n"
        elif ch == "?" and current.endswith("?"):
            piece = "\\?"  # never form a trigraph
        else:
            piece = ch
        current += piece
        if ch == "\n" or len(current) >= width:
            out.append(current)
            current = ""
    if current:
        out.append(current)
    return out


def main():
    page = read("index.html")
    css, js = read("app.css"), read("app.js")
    if "</script" in js.lower():
        sys.exit("app.js must not contain a closing script tag")
    page = page.replace("/*@CSS@*/", compact_css(css)).replace("/*@JS@*/", compact_js(js))
    page = "\n".join(line.strip() for line in page.splitlines() if line.strip())
    body = "\n".join('    "%s"' % line for line in c_literal_lines(page))
    header = (
        "#ifndef REMOTE_CONTROL_WEBAPP_H\n"
        "#define REMOTE_CONTROL_WEBAPP_H\n\n"
        "/* Generated by scripts/generate_remote_webapp.py from src/network/webapp/.\n"
        " * Do not edit by hand: change the sources and rerun the script. */\n"
        "static const char * const REMOTE_CONTROL_APP_HTML =\n"
        + body + ";\n\n"
        "#endif /* REMOTE_CONTROL_WEBAPP_H */\n"
    )
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(header)
    print("wrote %s (%d bytes of HTML)" % (os.path.relpath(OUT, ROOT), len(page.encode("utf-8"))))


if __name__ == "__main__":
    main()
