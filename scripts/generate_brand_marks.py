#!/usr/bin/env python3
"""Builds src/ui/brand_marks.c from assets/brand/*.svg.

The Compás wordmark is embedded as an LV_COLOR_FORMAT_A8 image (alpha
only), so the UI tints it with any theme colour through image_recolor. Its
size is for the 480px-wide reference panel; smaller boards scale it at draw
time. Needs ImageMagick (`magick`) and Pillow. Run from
the repository root after changing an SVG.
"""
import io
import os
import re
import subprocess

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MARKS = [
    # (C name, source SVG, target height in px at the 480px reference width)
    ("brand_wordmark", "assets/brand/compas-wordmark.svg", 80),
]


def rasterize(svg, height):
    # Render at 4x the target height (SVG user units are 96 dpi), then downsample.
    path = os.path.join(ROOT, svg)
    with open(path) as f:
        view_height = float(re.search(r'viewBox="[^"]*?(\S+)"', f.read()).group(1))
    density = 96 * 4 * height / view_height
    png = subprocess.run(["magick", "-background", "none", "-density", "%.2f" % density, path,
                          "-resize", "x%d" % height, "png:-"], check=True, capture_output=True).stdout
    return Image.open(io.BytesIO(png)).convert("RGBA").split()[3]


def main():
    body = ["/* Generated by scripts/generate_brand_marks.py from assets/brand/. Do not edit. */",
            '#include "brand_marks.h"', ""]
    for name, svg, height in MARKS:
        alpha = rasterize(svg, height)
        w, h = alpha.size
        data = alpha.tobytes()
        rows = ",\n".join("    " + ",".join(str(b) for b in data[i:i + 32]) for i in range(0, len(data), 32))
        body += ["static const uint8_t %s_a8[%d] = {\n%s\n};" % (name, len(data), rows), "",
                 "const lv_image_dsc_t %s = {" % name,
                 "    .header = { .magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_A8,",
                 "                .w = %d, .h = %d, .stride = %d }," % (w, h, w),
                 "    .data_size = sizeof(%s_a8)," % name,
                 "    .data = %s_a8," % name,
                 "};", ""]
        print("%s: %dx%d" % (name, w, h))
    with open(os.path.join(ROOT, "src", "ui", "brand_marks.c"), "w") as f:
        f.write("\n".join(body))


if __name__ == "__main__":
    main()
