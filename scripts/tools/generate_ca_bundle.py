#!/usr/bin/env python3
"""Regenerate src/network/security/ca_bundle.c from Mozilla's CA list.

Usage: generate_ca_bundle.py CACERT_PEM

CACERT_PEM must be curl's extract of the Mozilla root store
(https://curl.se/ca/cacert.pem, checked against cacert.pem.sha256). A system
trust store is refused: it can hold locally added CAs that must never ship.
"""
import re
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parents[2] / "src/network/security/ca_bundle.c"


def main() -> None:
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    text = Path(sys.argv[1]).read_text(encoding="utf-8")
    stamp = re.search(r"^## Certificate data from Mozilla as of: (.+)$", text, re.M)
    if not stamp:
        sys.exit("not curl's Mozilla CA extract (missing its header)")
    blocks = re.findall(r"^([^\n#=][^\n]*)\n=+\n(?:#[^\n]*\n)*(-----BEGIN CERTIFICATE-----\n.*?-----END CERTIFICATE-----\n)",
                        text, re.M | re.S)
    if not blocks:
        sys.exit("no certificates found")
    pem = "".join(f"# {name.strip()}\n{body}" for name, body in blocks).encode("utf-8") + b"\0"
    rows = [",".join(str(b) for b in pem[i:i + 20]) for i in range(0, len(pem), 20)]
    OUT.write_text(
        "/* Mozilla CA certificate bundle used to verify HTTPS server certificates.\n"
        f" * Generated by scripts/tools/generate_ca_bundle.py from curl's extract of the\n"
        f" * Mozilla root store ({stamp.group(1).strip()}, {len(blocks)} certificates). */\n\n"
        '#include "ca_bundle.h"\n\n'
        "const unsigned char ca_bundle_pem[] = {\n    " + ",\n    ".join(rows) + "\n};\n"
        f"const unsigned int ca_bundle_pem_len = {len(pem)};\n",
        encoding="ascii")
    print(f"{OUT}: {len(blocks)} certificates, {len(pem)} bytes")


if __name__ == "__main__":
    main()
