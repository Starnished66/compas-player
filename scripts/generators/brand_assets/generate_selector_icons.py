#!/usr/bin/env python3
"""Builds src/bootloader/selector/assets/icons/selector_icons*.c from Breeze symbolic SVGs.

Each icon is rasterised at high density; only the alpha channel is stored
(A8) and tinted at draw time. One utilities size is linked per panel width
(40px on 480-wide boards, 32px on 320-wide). Needs ImageMagick (`magick`)
and Pillow. Run from the repository root after changing an SVG.

--verify writes into a temp directory and compares against the tracked C
files.
"""
import argparse
import filecmp
import io
import os
import shutil
import subprocess
import sys
import tempfile

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))
SVG_DIR = os.path.join("assets", "bootloader", "selector", "icons")
OUT_DIR = os.path.join("src", "bootloader", "selector", "assets", "icons")
DENSITY = 96.0 * 8

# (C suffix, svg stem, pixel size)
UTILITIES_480 = (("utilities_40", "applications-utilities-symbolic", 40),)
UTILITIES_320 = (("utilities_32", "applications-utilities-symbolic", 32),)
NAV = (
    ("back_32", "go-previous-symbolic", 32),
    ("next_22", "go-next-symbolic", 22),
)
TOOLS = (
    ("adb_32", "debug-run-symbolic", 32),
    ("script_32", "run-build-symbolic", 32),
    ("mount_32", "media-mount-symbolic", 32),
    ("repair_32", "tools-wizard-symbolic", 32),
    ("reboot_32", "system-reboot-symbolic", 32),
    ("shutdown_32", "system-shutdown-symbolic", 32),
    ("recovery_32", "system-upgrade-symbolic", 32),
)

TRACKED = (
    "selector_icons.h",
    "selector_icons.c",
    "selector_icons_utilities_480.c",
    "selector_icons_utilities_320.c",
    "selector_icons_nav.c",
    "selector_icons_tools.c",
)


def magick_png(svg_path, size):
    png = subprocess.run(
        ["magick", "-background", "none", "-density", "%.2f" % DENSITY, svg_path,
         "-resize", "%dx%d" % (size, size), "png:-"],
        check=True, capture_output=True).stdout
    im = Image.open(io.BytesIO(png)).convert("RGBA")
    if im.size != (size, size):
        canvas = Image.new("RGBA", (size, size), (0, 0, 0, 0))
        canvas.paste(im, ((size - im.width) // 2, (size - im.height) // 2), im)
        im = canvas
    return im


def raster_a8(stem, size):
    path = os.path.join(ROOT, SVG_DIR, stem + ".svg")
    if not os.path.isfile(path):
        raise SystemExit("missing SVG %s" % path)
    return magick_png(path, size).split()[-1]


def c_bytes(data, per_line):
    lines = []
    for i in range(0, len(data), per_line):
        chunk = data[i:i + per_line]
        lines.append("    " + ",".join(str(b) for b in chunk))
    return ",\n".join(lines)


def write_file(out_root, relpath, text):
    path = os.path.join(out_root, relpath)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write(text)
        if not text.endswith("\n"):
            f.write("\n")


def emit_group(out_root, filename, icons):
    parts = [
        "/* Generated by scripts/generators/brand_assets/generate_selector_icons.py. Do not edit. */",
        '#include "../logos/selector_logos.h"',
        "",
    ]
    for suffix, stem, size in icons:
        alpha = raster_a8(stem, size)
        data = alpha.tobytes()
        name = "selector_icon_%s" % suffix
        parts.append("static const uint8_t %s_a8[%d] = {" % (name, len(data)))
        parts.append(c_bytes(data, 32))
        parts.append("};")
        parts.append("")
        parts.append("const selector_logo_a8_t %s = { %d, %d, %s_a8 };" % (
            name, alpha.size[0], alpha.size[1], name))
        parts.append("")
        print("%s: %dx%d A8" % (name, alpha.size[0], alpha.size[1]))
    write_file(out_root, os.path.join(OUT_DIR, filename), "\n".join(parts))


def emit_header(out_root):
    write_file(out_root, os.path.join(OUT_DIR, "selector_icons.h"), """\
#ifndef BOOTLOADER_SELECTOR_ICONS_H
#define BOOTLOADER_SELECTOR_ICONS_H

#include "../logos/selector_logos.h"

/* Embedded Breeze symbolic icons as A8 masks (stride = width), tinted at
 * draw time. The linked utilities raster is chosen at compile time from
 * BOARD_SCREEN_WIDTH. Generated by scripts/generators/brand_assets/generate_selector_icons.py. */

typedef enum {
    SELECTOR_ICON_UTILITIES = 0,
    SELECTOR_ICON_BACK,
    SELECTOR_ICON_NEXT,
    SELECTOR_ICON_ADB,
    SELECTOR_ICON_SCRIPT,
    SELECTOR_ICON_MOUNT,
    SELECTOR_ICON_REPAIR,
    SELECTOR_ICON_REBOOT,
    SELECTOR_ICON_SHUTDOWN,
    SELECTOR_ICON_RECOVERY
} selector_icon_id_t;

const selector_logo_a8_t * selector_icon(selector_icon_id_t id);

#endif /* BOOTLOADER_SELECTOR_ICONS_H */
""")


def emit_dispatch(out_root):
    write_file(out_root, os.path.join(OUT_DIR, "selector_icons.c"), """\
/* Generated by scripts/generators/brand_assets/generate_selector_icons.py. Do not edit. */
#include "selector_icons.h"
#include "../../../../core/system/runtime/board_config.h"

#include <stddef.h>

#if BOARD_SCREEN_WIDTH >= 400
extern const selector_logo_a8_t selector_icon_utilities_40;
#define SELECTOR_ICON_UTILITIES_OBJ selector_icon_utilities_40
#else
extern const selector_logo_a8_t selector_icon_utilities_32;
#define SELECTOR_ICON_UTILITIES_OBJ selector_icon_utilities_32
#endif

extern const selector_logo_a8_t selector_icon_back_32;
extern const selector_logo_a8_t selector_icon_next_22;
extern const selector_logo_a8_t selector_icon_adb_32;
extern const selector_logo_a8_t selector_icon_script_32;
extern const selector_logo_a8_t selector_icon_mount_32;
extern const selector_logo_a8_t selector_icon_repair_32;
extern const selector_logo_a8_t selector_icon_reboot_32;
extern const selector_logo_a8_t selector_icon_shutdown_32;
extern const selector_logo_a8_t selector_icon_recovery_32;

const selector_logo_a8_t * selector_icon(selector_icon_id_t id) {
    switch (id) {
        case SELECTOR_ICON_UTILITIES: return &SELECTOR_ICON_UTILITIES_OBJ;
        case SELECTOR_ICON_BACK: return &selector_icon_back_32;
        case SELECTOR_ICON_NEXT: return &selector_icon_next_22;
        case SELECTOR_ICON_ADB: return &selector_icon_adb_32;
        case SELECTOR_ICON_SCRIPT: return &selector_icon_script_32;
        case SELECTOR_ICON_MOUNT: return &selector_icon_mount_32;
        case SELECTOR_ICON_REPAIR: return &selector_icon_repair_32;
        case SELECTOR_ICON_REBOOT: return &selector_icon_reboot_32;
        case SELECTOR_ICON_SHUTDOWN: return &selector_icon_shutdown_32;
        case SELECTOR_ICON_RECOVERY: return &selector_icon_recovery_32;
        default: return NULL;
    }
}
""")


def generate(out_root):
    emit_group(out_root, "selector_icons_utilities_480.c", UTILITIES_480)
    emit_group(out_root, "selector_icons_utilities_320.c", UTILITIES_320)
    emit_group(out_root, "selector_icons_nav.c", NAV)
    emit_group(out_root, "selector_icons_tools.c", TOOLS)
    emit_dispatch(out_root)
    emit_header(out_root)


def verify():
    tmp = tempfile.mkdtemp(prefix="selector-icons-")
    try:
        generate(tmp)
        stale = []
        for name in TRACKED:
            rel = os.path.join(OUT_DIR, name)
            expected = os.path.join(tmp, rel)
            actual = os.path.join(ROOT, rel)
            if not os.path.isfile(actual) or not filecmp.cmp(expected, actual, shallow=False):
                stale.append(rel)
        if stale:
            sys.stderr.write("selector icons are stale; run python3 scripts/generators/brand_assets/generate_selector_icons.py\n")
            for path in stale:
                sys.stderr.write("  %s\n" % path)
            sys.exit(1)
        print("selector icons match scripts/generators/brand_assets/generate_selector_icons.py")
    finally:
        shutil.rmtree(tmp)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--verify", action="store_true",
                        help="fail if committed C arrays do not match a fresh raster")
    args = parser.parse_args()
    os.chdir(ROOT)
    if args.verify:
        verify()
    else:
        generate(ROOT)


if __name__ == "__main__":
    main()
