#!/usr/bin/env python3
"""Builds src/bootloader/selector/assets/logos/selector_logos*.c from the selector SVG sources.

The Compás wordmark is an A8 (alpha) image tinted at draw time. The Rockbox
banner is RGBA. One raster per panel width (480 and 320). Needs ImageMagick
(`magick`) and Pillow. Run from the repository root after changing an SVG.

Each bootloader links only the width matching BOARD_SCREEN_WIDTH. The
standalone R3II 2025 loader also omits the Rockbox arrays.
"""
import argparse
import filecmp
import io
import os
import re
import shutil
import subprocess
import sys
import tempfile

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))
WORDMARK_SVG = "assets/brand/compas-wordmark.svg"
ROCKBOX_SVG = "assets/bootloader/selector/rockbox-logo.svg"
OUT_DIR = os.path.join("src", "bootloader", "selector", "assets", "logos")

# Heights match the signed-off mock-up (38/26 wordmark, 50/34 Rockbox banner).
WORDMARK_HEIGHTS = (("480", 38), ("320", 26))
ROCKBOX_HEIGHTS = (("480", 50), ("320", 34))

TRACKED = (
    "selector_logos.h",
    "selector_logos.c",
    "selector_logos_wordmark_480.c",
    "selector_logos_wordmark_320.c",
    "selector_logos_rockbox_480.c",
    "selector_logos_rockbox_320.c",
)


def magick_png(svg, height, density):
    path = os.path.join(ROOT, svg)
    png = subprocess.run(
        ["magick", "-background", "none", "-density", "%.2f" % density, path,
         "-resize", "x%d" % height, "png:-"],
        check=True, capture_output=True).stdout
    return Image.open(io.BytesIO(png)).convert("RGBA")


def rasterize_wordmark(height):
    path = os.path.join(ROOT, WORDMARK_SVG)
    with open(path) as f:
        view_height = float(re.search(r'viewBox="[^"]*?(\S+)"', f.read()).group(1))
    density = 96 * 4 * height / view_height
    im = magick_png(WORDMARK_SVG, height, density)
    bbox = im.getbbox()
    return im.crop(bbox) if bbox else im


def rasterize_rockbox(height):
    """Official logo SVG includes a full-canvas black backing rect. Rasterize
    large, keep the gold plate, then scale to the target height."""
    path = os.path.join(ROOT, ROCKBOX_SVG)
    with open(path) as f:
        view_height = float(re.search(r'viewBox="[^"]+\s+(\S+)"', f.read()).group(1))
    work_height = max(height * 4, 200)
    density = 96 * 4 * work_height / view_height
    im = magick_png(ROCKBOX_SVG, work_height, density)
    px = im.load()
    w, h = im.size
    minx, miny, maxx, maxy = w, h, 0, 0
    found = False
    for y in range(h):
        for x in range(w):
            r, g, b, a = px[x, y]
            if a <= 20:
                continue
            if r < 20 and g < 20 and b < 20:
                continue
            found = True
            if x < minx:
                minx = x
            if y < miny:
                miny = y
            if x > maxx:
                maxx = x
            if y > maxy:
                maxy = y
    if not found:
        raise SystemExit("Rockbox logo raster had no non-black pixels")
    plate = im.crop((minx, miny, maxx + 1, maxy + 1))
    dest_w = max(1, int(round(plate.width * height / plate.height)))
    return plate.resize((dest_w, height), Image.Resampling.LANCZOS)


def c_bytes(data, per_line):
    lines = []
    for i in range(0, len(data), per_line):
        chunk = data[i:i + per_line]
        lines.append("    " + ",".join(str(b) for b in chunk))
    return ",\n".join(lines)


def write_file(out_root, relpath, text):
    path = os.path.join(out_root, relpath)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write(text)
        if not text.endswith("\n"):
            f.write("\n")


def emit_wordmark(out_root, suffix, im):
    alpha = im.split()[3]
    data = alpha.tobytes()
    name = "selector_wordmark_%s" % suffix
    parts = [
        "/* Generated by scripts/generators/brand_assets/generate_selector_logos.py. Do not edit. */",
        '#include "selector_logos.h"',
        "",
        "static const uint8_t %s_a8[%d] = {" % (name, len(data)),
        c_bytes(data, 32),
        "};",
        "",
        "const selector_logo_a8_t %s = { %d, %d, %s_a8 };" % (
            name, alpha.size[0], alpha.size[1], name),
        "",
    ]
    write_file(out_root, os.path.join(OUT_DIR, "selector_logos_wordmark_%s.c" % suffix),
               "\n".join(parts))
    print("%s: %dx%d A8" % (name, alpha.size[0], alpha.size[1]))


def emit_rockbox(out_root, suffix, im):
    data = im.tobytes()
    name = "selector_rockbox_%s" % suffix
    parts = [
        "/* Generated by scripts/generators/brand_assets/generate_selector_logos.py. Do not edit. */",
        '#include "selector_logos.h"',
        "",
        "static const uint8_t %s_rgba[%d] = {" % (name, len(data)),
        c_bytes(data, 80),
        "};",
        "",
        "const selector_logo_rgba_t %s = { %d, %d, %s_rgba };" % (
            name, im.size[0], im.size[1], name),
        "",
    ]
    write_file(out_root, os.path.join(OUT_DIR, "selector_logos_rockbox_%s.c" % suffix),
               "\n".join(parts))
    print("%s: %dx%d RGBA" % (name, im.size[0], im.size[1]))


def emit_dispatch(out_root):
    write_file(out_root, os.path.join(OUT_DIR, "selector_logos.c"), """\
/* Generated by scripts/generators/brand_assets/generate_selector_logos.py. Do not edit. */
#include "selector_logos.h"
#include "../../../../core/system/runtime/board_config.h"

#include <stddef.h>

#if BOARD_SCREEN_WIDTH >= 400
extern const selector_logo_a8_t selector_wordmark_480;
const selector_logo_a8_t * selector_logo_wordmark(void) {
    return &selector_wordmark_480;
}
#else
extern const selector_logo_a8_t selector_wordmark_320;
const selector_logo_a8_t * selector_logo_wordmark(void) {
    return &selector_wordmark_320;
}
#endif

#if defined(BOARD_R3II_2025)
const selector_logo_rgba_t * selector_logo_rockbox(void) {
    return NULL;
}
#elif BOARD_SCREEN_WIDTH >= 400
extern const selector_logo_rgba_t selector_rockbox_480;
const selector_logo_rgba_t * selector_logo_rockbox(void) {
    return &selector_rockbox_480;
}
#else
extern const selector_logo_rgba_t selector_rockbox_320;
const selector_logo_rgba_t * selector_logo_rockbox(void) {
    return &selector_rockbox_320;
}
#endif
""")


def emit_header(out_root):
    write_file(out_root, os.path.join(OUT_DIR, "selector_logos.h"), """\
#ifndef BOOTLOADER_SELECTOR_LOGOS_H
#define BOOTLOADER_SELECTOR_LOGOS_H

#include <stdint.h>

/* Embedded selector marks. Wordmark pixels are A8 (stride = width), tinted
 * at draw time. Rockbox pixels are RGBA8888 (stride = width * 4). Generated
 * from assets/brand/compas-wordmark.svg and
 * assets/bootloader/selector/rockbox-logo.svg.
 *
 * The linked raster is chosen at compile time from BOARD_SCREEN_WIDTH.
 * selector_logo_rockbox() is NULL on boards that never show a Rockbox row. */

typedef struct {
    int width;
    int height;
    const uint8_t * pixels;
} selector_logo_a8_t;

typedef struct {
    int width;
    int height;
    const uint8_t * pixels;
} selector_logo_rgba_t;

const selector_logo_a8_t * selector_logo_wordmark(void);
const selector_logo_rgba_t * selector_logo_rockbox(void);

#endif /* BOOTLOADER_SELECTOR_LOGOS_H */
""")


def generate(out_root):
    for suffix, height in WORDMARK_HEIGHTS:
        emit_wordmark(out_root, suffix, rasterize_wordmark(height))
    for suffix, height in ROCKBOX_HEIGHTS:
        emit_rockbox(out_root, suffix, rasterize_rockbox(height))
    emit_dispatch(out_root)
    emit_header(out_root)


def verify():
    tmp = tempfile.mkdtemp(prefix="selector-logos-")
    try:
        generate(tmp)
        stale = []
        for name in TRACKED:
            rel = os.path.join(OUT_DIR, name)
            expected = os.path.join(tmp, rel)
            actual = os.path.join(ROOT, rel)
            if not os.path.isfile(actual) or not filecmp.cmp(expected, actual, shallow=False):
                stale.append(rel)
        if stale:
            sys.stderr.write("selector logos are stale; run python3 scripts/generators/brand_assets/generate_selector_logos.py\n")
            for path in stale:
                sys.stderr.write("  %s\n" % path)
            sys.exit(1)
        print("selector logos match scripts/generators/brand_assets/generate_selector_logos.py")
    finally:
        shutil.rmtree(tmp)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--verify", action="store_true",
                        help="fail if committed C arrays do not match a fresh raster")
    args = parser.parse_args()
    os.chdir(ROOT)
    if args.verify:
        verify()
    else:
        generate(ROOT)


if __name__ == "__main__":
    main()
