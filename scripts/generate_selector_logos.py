#!/usr/bin/env python3
"""Builds src/bootloader/selector_logos*.c from the selector SVG sources.

The Compás wordmark is an A8 (alpha) image tinted at draw time. The Rockbox
banner is RGBA. One raster per panel width (480 and 320). Needs ImageMagick
(`magick`) and Pillow. Run from the repository root after changing an SVG.
"""
import argparse
import io
import os
import re
import subprocess
import sys

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
WORDMARK_SVG = "assets/brand/compas-wordmark.svg"
ROCKBOX_SVG = "assets/bootloader/selector/rockbox-logo.svg"
OUT_DIR = os.path.join("src", "bootloader")

# Heights match the signed-off mock-up (38/26 wordmark, 50/34 Rockbox banner).
WORDMARK_HEIGHTS = (("480", 38), ("320", 26))
ROCKBOX_HEIGHTS = (("480", 50), ("320", 34))


def magick_png(svg, height, density):
    path = os.path.join(ROOT, svg)
    png = subprocess.run(
        ["magick", "-background", "none", "-density", "%.2f" % density, path,
         "-resize", "x%d" % height, "png:-"],
        check=True, capture_output=True).stdout
    return Image.open(io.BytesIO(png)).convert("RGBA")


def rasterize_wordmark(height):
    path = os.path.join(ROOT, WORDMARK_SVG)
    with open(path) as f:
        view_height = float(re.search(r'viewBox="[^"]*?(\S+)"', f.read()).group(1))
    density = 96 * 4 * height / view_height
    im = magick_png(WORDMARK_SVG, height, density)
    bbox = im.getbbox()
    return im.crop(bbox) if bbox else im


def rasterize_rockbox(height):
    """Official logo SVG includes a full-canvas black backing rect. Rasterize
    large, keep the gold plate, then scale to the target height."""
    path = os.path.join(ROOT, ROCKBOX_SVG)
    with open(path) as f:
        view_height = float(re.search(r'viewBox="[^"]+\s+(\S+)"', f.read()).group(1))
    work_height = max(height * 4, 200)
    density = 96 * 4 * work_height / view_height
    im = magick_png(ROCKBOX_SVG, work_height, density)
    px = im.load()
    w, h = im.size
    minx, miny, maxx, maxy = w, h, 0, 0
    found = False
    for y in range(h):
        for x in range(w):
            r, g, b, a = px[x, y]
            if a <= 20:
                continue
            if r < 20 and g < 20 and b < 20:
                continue
            found = True
            if x < minx:
                minx = x
            if y < miny:
                miny = y
            if x > maxx:
                maxx = x
            if y > maxy:
                maxy = y
    if not found:
        raise SystemExit("Rockbox logo raster had no non-black pixels")
    plate = im.crop((minx, miny, maxx + 1, maxy + 1))
    dest_w = max(1, int(round(plate.width * height / plate.height)))
    return plate.resize((dest_w, height), Image.Resampling.LANCZOS)


def c_bytes(data, per_line):
    lines = []
    for i in range(0, len(data), per_line):
        chunk = data[i:i + per_line]
        lines.append("    " + ",".join(str(b) for b in chunk))
    return ",\n".join(lines)


def write_file(relpath, text):
    path = os.path.join(ROOT, relpath)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write(text)
        if not text.endswith("\n"):
            f.write("\n")


def emit_wordmark(images):
    parts = ["/* Generated by scripts/generate_selector_logos.py. Do not edit. */",
             '#include "selector_logos.h"', ""]
    for suffix, im in images:
        alpha = im.split()[3]
        data = alpha.tobytes()
        name = "selector_wordmark_%s" % suffix
        parts += [
            "static const uint8_t %s_a8[%d] = {" % (name, len(data)),
            c_bytes(data, 32),
            "};",
            "",
            "const selector_logo_a8_t %s = { %d, %d, %s_a8 };" % (
                name, alpha.size[0], alpha.size[1], name),
            "",
        ]
        print("%s: %dx%d A8" % (name, alpha.size[0], alpha.size[1]))
    write_file(os.path.join(OUT_DIR, "selector_logos_wordmark.c"), "\n".join(parts))


def emit_rockbox(suffix, im):
    data = im.tobytes()
    name = "selector_rockbox_%s" % suffix
    parts = [
        "/* Generated by scripts/generate_selector_logos.py. Do not edit. */",
        '#include "selector_logos.h"',
        "",
        "static const uint8_t %s_rgba[%d] = {" % (name, len(data)),
        c_bytes(data, 80),
        "};",
        "",
        "const selector_logo_rgba_t %s = { %d, %d, %s_rgba };" % (
            name, im.size[0], im.size[1], name),
        "",
    ]
    write_file(os.path.join(OUT_DIR, "selector_logos_rockbox_%s.c" % suffix),
               "\n".join(parts))
    print("%s: %dx%d RGBA" % (name, im.size[0], im.size[1]))


def emit_dispatch():
    write_file(os.path.join(OUT_DIR, "selector_logos.c"), """\
/* Generated by scripts/generate_selector_logos.py. Do not edit. */
#include "selector_logos.h"

const selector_logo_a8_t * selector_logo_wordmark(int canvas_width) {
    return canvas_width >= 400 ? &selector_wordmark_480 : &selector_wordmark_320;
}

const selector_logo_rgba_t * selector_logo_rockbox(int canvas_width) {
    return canvas_width >= 400 ? &selector_rockbox_480 : &selector_rockbox_320;
}
""")


def emit_header():
    write_file(os.path.join(OUT_DIR, "selector_logos.h"), """\
#ifndef BOOTLOADER_SELECTOR_LOGOS_H
#define BOOTLOADER_SELECTOR_LOGOS_H

#include <stdint.h>

/* Embedded selector marks. Wordmark pixels are A8 (stride = width), tinted
 * at draw time. Rockbox pixels are RGBA8888 (stride = width * 4). Generated
 * from assets/brand/compas-wordmark.svg and
 * assets/bootloader/selector/rockbox-logo.svg. */

typedef struct {
    int width;
    int height;
    const uint8_t * pixels;
} selector_logo_a8_t;

typedef struct {
    int width;
    int height;
    const uint8_t * pixels;
} selector_logo_rgba_t;

extern const selector_logo_a8_t selector_wordmark_480;
extern const selector_logo_a8_t selector_wordmark_320;
extern const selector_logo_rgba_t selector_rockbox_480;
extern const selector_logo_rgba_t selector_rockbox_320;

const selector_logo_a8_t * selector_logo_wordmark(int canvas_width);
const selector_logo_rgba_t * selector_logo_rockbox(int canvas_width);

#endif /* BOOTLOADER_SELECTOR_LOGOS_H */
""")


def generate():
    wordmarks = [(suffix, rasterize_wordmark(height)) for suffix, height in WORDMARK_HEIGHTS]
    emit_wordmark(wordmarks)
    for suffix, height in ROCKBOX_HEIGHTS:
        emit_rockbox(suffix, rasterize_rockbox(height))
    emit_dispatch()
    emit_header()


def verify():
    tracked = [
        os.path.join(OUT_DIR, name) for name in (
            "selector_logos.h",
            "selector_logos.c",
            "selector_logos_wordmark.c",
            "selector_logos_rockbox_480.c",
            "selector_logos_rockbox_320.c",
        )
    ]
    before = {}
    for path in tracked:
        with open(os.path.join(ROOT, path), "rb") as f:
            before[path] = f.read()
    generate()
    stale = []
    for path in tracked:
        with open(os.path.join(ROOT, path), "rb") as f:
            after = f.read()
        if after != before[path]:
            stale.append(path)
            with open(os.path.join(ROOT, path), "wb") as f:
                f.write(before[path])
    if stale:
        sys.stderr.write("selector logos are stale; run python3 scripts/generate_selector_logos.py\n")
        for path in stale:
            sys.stderr.write("  %s\n" % path)
        sys.exit(1)
    print("selector logos match scripts/generate_selector_logos.py")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--verify", action="store_true",
                        help="fail if committed C arrays do not match a fresh raster")
    args = parser.parse_args()
    os.chdir(ROOT)
    if args.verify:
        verify()
    else:
        generate()


if __name__ == "__main__":
    main()
