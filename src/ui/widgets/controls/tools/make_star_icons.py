#!/usr/bin/env python3
"""Generate the shared rating icons."""
from pathlib import Path
import math
from PIL import Image, ImageDraw


def make_star(filled):
    scale = 4
    points = []
    for index in range(10):
        angle = -math.pi / 2 + index * math.pi / 5
        radius = 21.75 if index % 2 == 0 else 9
        points.append(((24 + radius * math.cos(angle)) * scale,
                       (24 + radius * math.sin(angle)) * scale))
    image = Image.new('L', (48 * scale, 48 * scale))
    draw = ImageDraw.Draw(image)
    if filled:
        draw.polygon(points, fill=255)
    else:
        draw.line(points + [points[0]], fill=255, width=6, joint='curve')
    return image.resize((48, 48), Image.Resampling.LANCZOS)


def descriptor(name, filled):
    data = make_star(filled).tobytes()
    rows = ["    " + ", ".join(f"0x{v:02x}" for v in data[i:i + 16]) + ","
            for i in range(0, len(data), 16)]
    return (f"static const uint8_t {name}_data[] = {{\n" + "\n".join(rows) +
            f"\n}};\n\nconst lv_image_dsc_t {name} = {{\n"
            "    .header = { .magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_A8,\n"
            "                .w = 48, .h = 48, .stride = 48 },\n"
            f"    .data_size = sizeof({name}_data),\n    .data = {name}_data\n}};\n")


def main():
    output = Path(__file__).resolve().parents[1] / 'star_rating_icons.c'
    content = '/* Generated by tools/make_star_icons.py. */\n#include "star_rating_icons.h"\n\n'
    content += "\n".join(descriptor(name, filled) for name, filled in
                         (("star_rating_icon_on", True), ("star_rating_icon_off", False)))
    output.write_text(content)


if __name__ == '__main__':
    main()
