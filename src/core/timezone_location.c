static int compare_id(const char * key, const char * id) {
    return strcmp(key, id);
}

bool timezone_location_get(const char * iana_id,
                           int32_t * latitude_millidegrees,
                           int32_t * longitude_millidegrees) {
    if (!iana_id || !iana_id[0] || !latitude_millidegrees || !longitude_millidegrees)
        return false;

    size_t lo = 0;
    size_t hi = sizeof(timezone_locations) / sizeof(timezone_locations[0]);
    while (lo < hi) {
        size_t mid = lo + (hi - lo) / 2;
        int cmp = compare_id(iana_id, timezone_locations[mid].iana_id);
        if (cmp == 0) {
            *latitude_millidegrees = timezone_locations[mid].latitude_millidegrees;
            *longitude_millidegrees = timezone_locations[mid].longitude_millidegrees;
            return true;
        }
        if (cmp < 0) hi = mid;
        else lo = mid + 1;
    }
    return false;
}
